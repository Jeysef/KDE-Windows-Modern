#!/usr/bin/env python3
"""Generate the derived task-button frames of tasks.svg from the bottom ones.

Plasma's task manager (Icon Tasks) asks for a frame prefix per state and
panel edge. For a hovered task it tries "<state>-hover" before falling back
to "hover"; on top/left/right panels it adds "north-", "west-", "east-".
The theme only drew the plain states for a bottom panel by hand, so:

  * hovering any task fell back to "hover", whose centre carries the blue
    active bar: an open but inactive app looked active under the pointer,
    and a pinned app that is not running ("launcher-hover") got no tile;
  * the top/left/right frames were drawn separately and had drifted (bar at
    the wrong edge, a misnamed top-panel piece).

This script, run on each variant's tasks.svg:

  1. puts the state bars 1.5 units (about 2.5 px on a 48 px panel) above
     the bottom of the tile, not flush with its edge;
  2. builds "<state>-hover" for normal, minimized, attention and focus, and
     "launcher-hover", from the hover tile plus that state's own bar;
  3. builds every north-/west-/east- frame from the bottom one, flipped or
     rotated, so all edges are the same design turned round.

Generated elements live in one marked block before </svg>; re-running
replaces it. The file is edited as text, never re-serialised (an XML
round-trip once renamed xlink:href and broke the theme).

Usage: scripts/theme/tasks-frames.py plasma/desktoptheme/*/widgets/tasks.svg
"""
import re
import sys
import xml.etree.ElementTree as ET

BEGIN, END = "<!-- tasks-frames.py: generated, do not edit -->", "<!-- tasks-frames.py: end -->"
PIECES = ("topleft", "top", "topright", "left", "center", "right", "bottomleft", "bottom", "bottomright")
BASE_STATES = ("normal", "hover", "focus", "attention", "minimized", "progress")
# hover variant -> (tile element, bar element or None, tile fill-opacity override or None)
HOVER = {
    "normal-hover": ("rect1929-2", "rect2616-7", None),
    "minimized-hover": ("rect1929-2", "rect2616-1", None),
    "attention-hover": ("rect1929-2", "rect2616-3-0", None),
    "focus-hover": ("rect1929", "rect2616", "brighter"),
    "launcher-hover": ("rect1929-2", None, None),
}
BARS = ("rect2616-7", "rect2616", "rect2616-3", "rect2616-1", "rect2616-3-0")
BAR_Y = "121.5"
FLIP, CW, CCW = "scale(1,-1)", "rotate(90)", "rotate(-90)"
EDGES = {
    "north": (FLIP, {"top": "bottom", "bottom": "top", "topleft": "bottomleft", "topright": "bottomright",
                     "bottomleft": "topleft", "bottomright": "topright",
                     "left": "left", "right": "right", "center": "center"}),
    "west": (CW, {"left": "bottom", "top": "left", "right": "top", "bottom": "right",
                  "topleft": "bottomleft", "topright": "topleft", "bottomright": "topright",
                  "bottomleft": "bottomright", "center": "center"}),
    "east": (CCW, {"right": "bottom", "top": "right", "left": "top", "bottom": "left",
                   "topright": "bottomright", "topleft": "topright", "bottomleft": "topleft",
                   "bottomright": "bottomleft", "center": "center"}),
}
OPEN = re.compile(r"<([a-zA-Z][\w:.-]*)\b[^<>]*?>", re.S)
ANY = re.compile(r"<(/?)([a-zA-Z][\w:.-]*)\b[^<>]*?(/?)>", re.S)


def element_span(text, start):
    m = OPEN.match(text, start)
    if m.group(0).endswith("/>"):
        return start, m.end()
    depth, pos = 1, m.end()
    while depth:
        t = ANY.search(text, pos)
        depth += -1 if t.group(1) else (0 if t.group(3) else 1)
        pos = t.end()
    return start, pos


def remove_ids(text, ids):
    removed = 0
    while True:
        m = next((m for m in re.finditer(r'<[a-zA-Z][^<>]*?\sid="([^"]+)"', text) if m.group(1) in ids), None)
        if not m:
            return text, removed
        s, e = element_span(text, m.start())
        ws = len(text[:s]) - len(text[:s].rstrip())
        text, removed = text[:s - ws] + text[e:], removed + 1


def set_attr(text, elem_id, attr, value):
    m = re.search(r'<[a-zA-Z][^<>]*?\sid="%s"[^<>]*>' % re.escape(elem_id), text)
    assert m, elem_id
    tag = m.group(0)
    new = re.sub(r'(\s%s=")[^"]*(")' % attr, r'\g<1>%s\2' % value, tag)
    assert f'{attr}="{value}"' in new, (elem_id, attr)
    return text[:m.start()] + new + text[m.end():]


def process(path):
    text = open(path).read()
    assert 'xmlns:xlink="http://www.w3.org/1999/xlink"' in text, f"{path}: the xlink namespace must be named xlink"
    # drop a previous generated block (and the first version's marker)
    text = re.sub(r"\s*" + re.escape(BEGIN) + r".*?" + re.escape(END), "", text, flags=re.S)
    text = re.sub(r"\s*<!-- Top/left/right task frames, generated by scripts/theme/tasks-edges.py[^>]*-->", "", text)
    states = BASE_STATES + tuple(HOVER)
    generated = {f"{e}-{s}-{p}" for e in EDGES for s in states for p in PIECES}
    generated |= {f"{s}-{p}" for s in HOVER for p in PIECES}
    text, removed = remove_ids(text, generated)
    text = re.sub(r'\s*<use\b[^<>]*\sid="use3099"[^<>]*/>', "", text)   # old misnamed north focus centre

    for bar in BARS:                                     # 1. padding under the bar
        text = set_attr(text, bar, "y", BAR_Y)

    out = [f"  {BEGIN}"]
    for state, (tile, bar, extra) in HOVER.items():      # 2. hover variants
        tile_use = f'<use xlink:href="#{tile}"/>'
        if extra == "brighter":                          # active + hover: one step brighter tile
            tile_use = f'<use xlink:href="#{tile}"/><use xlink:href="#{tile}" opacity="0.35"/>'
        bar_use = f'<use xlink:href="#{bar}"/>' if bar else ""
        out.append(f'  <g id="{state}-center">{tile_use}{bar_use}</g>')
        for p in PIECES:
            if p != "center":
                out.append(f'  <g id="{state}-{p}"><use xlink:href="#hover-{p}"/></g>')
    for edge, (transform, mapping) in EDGES.items():     # 3. other panel edges
        for state in states:
            for p in PIECES:
                out.append(f'  <g id="{edge}-{state}-{p}"><use xlink:href="#{state}-{mapping[p]}" transform="{transform}"/></g>')
    out.append(f"  {END}")
    text = text.replace("</svg>", "\n".join(out) + "\n</svg>", 1)

    ET.fromstring(text.encode())
    ids = set(re.findall(r'\sid="([^"]+)"', text))
    missing = [f"{s}-{p}" for s in states for p in PIECES if f"{s}-{p}" not in ids]
    assert not missing, f"{path}: missing {missing}"
    open(path, "w").write(text)
    print(f"{path}: removed {removed} old pieces, generated {len(out) - 2}")


for p in sys.argv[1:]:
    process(p)
